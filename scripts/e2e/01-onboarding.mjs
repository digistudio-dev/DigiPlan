export default async ({ page, shot, log }) => {
  await page.getByText('Bienvenue sur DigiPlan').waitFor({ timeout: 30_000 })
  await page.setViewportSize({ width: 1360, height: 860 }).catch(() => {})
  await shot('welcome')
  await page.getByRole('button', { name: /Commencer la configuration/ }).click()
  await page.getByRole('button', { name: /Barbier/ }).click()
  await shot('category')
  await page.getByRole('button', { name: /Continuer/ }).click()
  await page.locator('#b-name').fill('Barber House Maârif')
  await page.locator('#b-owner').fill('Youssef El Amrani')
  await page.locator('#b-phone').fill('0612345678')
  await page.locator('#b-city').fill('Casablanca')
  await shot('business')
  await page.getByRole('button', { name: /Continuer/ }).click()
  await page.getByText('Horaires d’ouverture').waitFor()
  await shot('hours')
  await page.getByRole('button', { name: /Continuer/ }).click()
  await page.locator('#s-name').fill('Youssef')
  await shot('staff')
  await page.getByRole('button', { name: /Continuer/ }).click()
  await page.getByText('Vos services').waitFor()
  await shot('services')
  await page.getByRole('button', { name: /Terminer la configuration/ }).click()
  await page.getByText('Tout est prêt').waitFor({ timeout: 15_000 })
  await shot('done')
  await page.getByRole('button', { name: /Commencer avec DigiPlan/ }).click()
  await page.getByText('Rendez-vous aujourd’hui').first().waitFor({ timeout: 15_000 })
  await page.waitForTimeout(800)
  await shot('dashboard')
  log('onboarding OK')
}
